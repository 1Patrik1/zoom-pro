-- Firemní identifikace při registraci a volitelné fakturační údaje externích členů
BEGIN;

ALTER TABLE "Company"
  ADD COLUMN IF NOT EXISTS ico TEXT,
  ADD COLUMN IF NOT EXISTS dic TEXT,
  ADD COLUMN IF NOT EXISTS street TEXT,
  ADD COLUMN IF NOT EXISTS city TEXT,
  ADD COLUMN IF NOT EXISTS zip TEXT,
  ADD COLUMN IF NOT EXISTS country TEXT DEFAULT 'CZ';

ALTER TABLE "User"
  ADD COLUMN IF NOT EXISTS ico TEXT,
  ADD COLUMN IF NOT EXISTS dic TEXT,
  ADD COLUMN IF NOT EXISTS street TEXT,
  ADD COLUMN IF NOT EXISTS city TEXT,
  ADD COLUMN IF NOT EXISTS zip TEXT,
  ADD COLUMN IF NOT EXISTS "employmentType" TEXT NOT NULL DEFAULT 'INTERNAL';

UPDATE "User"
   SET "employmentType" = 'EXTERNAL'
 WHERE ico IS NOT NULL OR dic IS NOT NULL OR street IS NOT NULL OR city IS NOT NULL OR zip IS NOT NULL;

COMMIT;
